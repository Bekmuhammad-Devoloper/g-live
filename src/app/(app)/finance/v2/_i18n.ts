export function fmtDate(locale: Locale, d: Date | string | null | undefined, withTime = false): string {
  if (!d) return "—";
  const date = typeof d === "string" ? new Date(d) : d;
  return new Intl.DateTimeFormat(locale === "ru" ? "ru-RU" : locale === "de" ? "de-DE" : locale === "en" ? "en-GB" : "uz-UZ", {
    timeZone: "Asia/Tashkent", dateStyle: "medium", ...(withTime ? { timeStyle: "short" } : {}),
  }).format(date);
}
